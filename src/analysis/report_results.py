"""Render ``reports/results.json`` into human-readable markdown.

    python -m src.analysis.report_results

Exists so that no metric in the documentation is ever typed by hand. The README
quotes ``reports/RESULTS.md``, which is generated here from the JSON that
``src.evaluation.run_experiments`` wrote. If an experiment has not been run, the
report says so rather than showing stale or invented numbers.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Sequence

from src.config import Config, load_config
from src.utils.logging_utils import get_logger

LOGGER = get_logger(__name__)

RESULTS_FILE = "results.json"
OUTPUT_FILE = "RESULTS.md"

MODEL_LABELS = {
    "popularity": "Popularity baseline",
    "content": "Content-based",
    "collaborative": "Collaborative filtering (item-item)",
    "matrix_factorization": "Matrix factorisation (SVD)",
    "hybrid": "Hybrid (tuned weights)",
    "next_destination": "Next-destination (transition-aware)",
    "learning_to_rank": "Learning-to-Rank (LightGBM)",
}


def _fmt(value: Any, digits: int = 4) -> str:
    """Format a number for a markdown table, tolerating None and NaN."""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "n/a"
    if number != number:  # NaN
        return "n/a"
    return f"{number:.{digits}f}"


def _accuracy_table(rows: Sequence[Dict[str, Any]], k: int) -> List[str]:
    """Markdown table of the accuracy metrics at one K."""
    lines = [
        f"| Model | Precision@{k} | Recall@{k} | F1@{k} | MAP@{k} | MRR@{k} | NDCG@{k} |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        label = MODEL_LABELS.get(str(row.get("model")), str(row.get("model")))
        lines.append(
            f"| {label} "
            f"| {_fmt(row.get(f'precision@{k}'))} "
            f"| {_fmt(row.get(f'recall@{k}'))} "
            f"| {_fmt(row.get(f'f1@{k}'))} "
            f"| {_fmt(row.get(f'map@{k}'))} "
            f"| {_fmt(row.get(f'mrr@{k}'))} "
            f"| {_fmt(row.get(f'ndcg@{k}'))} |"
        )
    return lines


def render(payload: Dict[str, Any]) -> str:
    """Build the full markdown results document."""
    dataset = payload.get("dataset", {})
    k_values = payload.get("k_values", [5, 10, 20])
    comparison = payload.get("model_comparison", [])
    beyond = payload.get("beyond_accuracy", [])
    importance = payload.get("feature_importance", [])
    weights = payload.get("hybrid_weights", {})

    lines: List[str] = [
        "# Experimental results",
        "",
        "> Generated by `python -m src.analysis.report_results` from "
        "`reports/results.json`. Every number below is measured by "
        "`src.evaluation.run_experiments`; none is typed by hand.",
        "",
        "## Dataset",
        "",
        f"- **{dataset.get('n_destinations', 'n/a')}** destinations across "
        f"**{dataset.get('n_countries', 'n/a')}** countries (real data)",
        f"- **{dataset.get('n_users', 'n/a')}** users and "
        f"**{dataset.get('n_interactions', 'n/a')}** trips "
        f"(**synthetic** — see the data provenance note)",
        f"- Split: {dataset.get('train_interactions', 'n/a')} train / "
        f"{dataset.get('validation_interactions', 'n/a')} validation / "
        f"{dataset.get('test_interactions', 'n/a')} test interactions, "
        "leave-last-n-out per user",
        "",
        "> **What these numbers mean.** The interactions are generated, so the "
        "metrics measure how well each model recovers the structure the "
        "generator injected (preference archetypes, geographic chaining and "
        "popularity bias). That is a genuine learning problem and it validates "
        "the pipeline end to end, but it is **not** evidence of real-world "
        "recommendation accuracy.",
        "",
        "## Accuracy",
        "",
    ]

    for k in k_values:
        lines.append(f"### K = {k}")
        lines.append("")
        lines.extend(_accuracy_table(comparison, k))
        lines.append("")

    recall = payload.get("candidate_recall_at_test")
    if recall is not None:
        lines += [
            "### Candidate generation",
            "",
            f"Stage-1 recall on the test split: **{_fmt(recall)}**. This is the "
            "ceiling on the two-stage system: any held-out destination that "
            "candidate generation discards cannot be recovered by the ranker.",
            "",
        ]

    if weights:
        lines += [
            "### Tuned hybrid weights",
            "",
            "Searched on the validation split by NDCG@10, never on test.",
            "",
            "| Component | Weight |",
            "|---|---:|",
        ]
        for name, value in weights.items():
            lines.append(f"| {name} | {_fmt(value, 2)} |")
        lines.append("")

    if beyond:
        lines += [
            "## Popularity bias, coverage and diversity",
            "",
            "Accuracy alone cannot distinguish a good recommender from one that "
            "shows everybody the same famous cities. Measured at K = 10:",
            "",
            "| Model | Catalog coverage | Unique shown | Gini | Mean popularity pct | From top decile | Novelty | Intra-list diversity | Geo spread (km) |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for row in beyond:
            label = MODEL_LABELS.get(str(row.get("model")), str(row.get("model")))
            lines.append(
                f"| {label} "
                f"| {_fmt(row.get('catalog_coverage'), 3)} "
                f"| {row.get('n_unique_recommended', 'n/a')} "
                f"| {_fmt(row.get('gini'), 3)} "
                f"| {_fmt(row.get('mean_popularity_percentile'), 3)} "
                f"| {_fmt(row.get('share_from_top_decile'), 3)} "
                f"| {_fmt(row.get('novelty'), 2)} "
                f"| {_fmt(row.get('intra_list_diversity'), 3)} "
                f"| {_fmt(row.get('geographic_spread_km'), 0)} |"
            )
        lines += [
            "",
            "- **Catalog coverage** — share of destinations that appear in at "
            "least one user's top 10.",
            "- **Gini** — concentration of exposure across the catalog "
            "(0 = perfectly even, 1 = one destination takes everything).",
            "- **From top decile** — share of recommendations drawn from the "
            "most popular 10% of destinations. A high value is the signature of "
            "a model that just recommends famous places.",
            "- **Novelty** — mean self-information of what is recommended; "
            "higher means less obvious choices.",
            "",
        ]

    most = payload.get("most_recommended", {})
    if most:
        lines += ["## What each model recommends most often", ""]
        for model, entries in most.items():
            if not entries:
                continue
            label = MODEL_LABELS.get(model, model)
            top = ", ".join(
                f"{entry.get('city')} ({entry.get('share_of_users', 0):.0%})"
                for entry in entries[:6]
            )
            lines.append(f"- **{label}**: {top}")
        lines.append("")

    if importance:
        lines += [
            "## What the ranker actually learned",
            "",
            "Gain-based feature importance from the LightGBM LambdaRank model. "
            "The explanation layer is constrained to these signals.",
            "",
            "| Feature | Gain share |",
            "|---|---:|",
        ]
        for row in importance[:15]:
            lines.append(f"| `{row.get('feature')}` | {_fmt(row.get('gain_share'), 3)} |")
        lines.append("")

    return "\n".join(lines)


def run(config: Config) -> str:
    """Read the results JSON and write the markdown report."""
    reports = config.path("reports")
    source = reports / RESULTS_FILE
    if not source.exists():
        message = (
            "# Experimental results\n\n"
            "No results yet. Run `python -m src.evaluation.run_experiments` to "
            "generate them.\n"
        )
        (reports / OUTPUT_FILE).write_text(message, encoding="utf-8")
        LOGGER.warning("%s not found; wrote a placeholder", source)
        return message

    payload = json.loads(source.read_text(encoding="utf-8"))
    document = render(payload)
    (reports / OUTPUT_FILE).write_text(document, encoding="utf-8")
    LOGGER.info("Wrote %s", reports / OUTPUT_FILE)
    return document


def main() -> None:
    parser = argparse.ArgumentParser(description="Render experiment results to markdown")
    parser.add_argument("--config", default=None)
    args = parser.parse_args()
    print(run(load_config(args.config)))


if __name__ == "__main__":
    main()
